// Roadster 88 multiplayer smoke test: two isolated browser contexts join the same online world, one drives, boosts and walks, the other checks it sees a remote Roadster and avatar, with screenshots from both.
// usage: node web/tools/mp-test.mjs [--map=valley] [--out=dir]
import { chromium } from '/Users/jurek/openclaw/node_modules/playwright-core/index.mjs';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const opt = (k, d) => { const a = args.find((x) => x.startsWith(`--${k}=`)); return a ? a.slice(a.indexOf('=') + 1) : d; };
const out = opt('out', path.resolve(here, '../../Niepotrzebne/shots-mp'));
const map = opt('map', 'valley');
fs.mkdirSync(out, { recursive: true });
const exe = '/Users/jurek/Library/Caches/ms-playwright/chromium-1234/chrome-mac-x64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing';
const browser = await chromium.launch({ headless: false, executablePath: exe, args: ['--use-angle=metal', '--ignore-gpu-blocklist', '--enable-unsafe-webgpu', '--window-size=1100,760', '--window-position=3000,3000', '--disable-background-timer-throttling', '--disable-renderer-backgrounding', '--disable-backgrounding-occluded-windows'] });
const url = `http://localhost:8788/web/?debug&jitter&q=medium&map=${map}`;
const open = async (tag) => {
  const ctx = await browser.newContext({ viewport: { width: 1100, height: 680 } });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(tag + ' pageerror: ' + e.message));
  page.on('console', (m) => { if (m.type() === 'error' && !m.text().includes('404')) errors.push(tag + ' ' + m.text()); if (m.text().includes('online')) console.log(tag, m.text()); });
  await page.goto(url, { waitUntil: 'load' });
  await page.waitForFunction(() => window.__r88 && window.__r88.game.started, null, { timeout: 120000 });
  return { page, errors };
};
const A = await open('A');
const B = await open('B');
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const st = (p) => p.evaluate(() => { const g = window.__r88.game, o = g.online; return { status: o.status, uid: o.uid && o.uid.slice(0, 6), room: o.room, remotes: o.remotes.size, name: o.name, pos: g.car.sim.pos.toArray ? g.car.sim.pos.toArray() : [g.car.sim.pos.x, g.car.sim.pos.y, g.car.sim.pos.z] }; });
for (let i = 0; i < 40; i++) { const a = await st(A.page), b = await st(B.page); if (a.remotes && b.remotes) break; await wait(500); }
await wait(1500);
console.log('weather', await A.page.evaluate(() => window.__r88.game.weather && window.__r88.game.weather.kind), await B.page.evaluate(() => window.__r88.game.weather && window.__r88.game.weather.kind));
console.log('A', JSON.stringify(await st(A.page)));
console.log('B', JSON.stringify(await st(B.page)));
await B.page.evaluate(() => { const g = window.__r88.game, r = [...g.online.remotes.values()][0]; if (r) { g.car.sim.teleport([r.pos.x, r.pos.y + 0.3, r.pos.z - 14], 0, 0); g.capture(g.car); g.capture(g.car); g.rig.initialized = false; } });
await wait(1500);
console.log('solid', await B.page.evaluate(() => [...window.__r88.game.online.remotes.values()].map((r) => r.solid).join(',')));
await A.page.evaluate(() => window.__r88.keys('KeyW')); await wait(1500);
await B.page.screenshot({ path: `${out}/B_sees_A_drive.png` });
await A.page.evaluate(() => window.__r88.keys('KeyW', 'ShiftLeft')); await wait(1200);
await B.page.screenshot({ path: `${out}/B_sees_A_boost.png` });
await A.page.evaluate(() => window.__r88.release()); await wait(3500);
await A.page.evaluate(() => window.__r88.keys('KeyS')); await wait(2500); await A.page.evaluate(() => window.__r88.release()); await wait(600);
await A.page.evaluate(() => window.__r88.tap('KeyF')); await wait(1200);
await A.page.evaluate(() => window.__r88.keys('KeyW')); await wait(1600);
await A.page.evaluate(() => window.__r88.release());
await B.page.evaluate(() => { const g = window.__r88.game, r = [...g.online.remotes.values()][0]; if (r) { const p = r.foot ? r.walk.pose : r.pos; g.rig.mode = 'chase'; g.car.sim.teleport([p.x - 6, p.y + 0.3, p.z - 8], 0.6, 0); g.capture(g.car); g.capture(g.car); g.rig.initialized = false; } });
await wait(1800);
await B.page.screenshot({ path: `${out}/B_sees_A_walk.png` });
await A.page.screenshot({ path: `${out}/A_view.png` });
console.log('B remote', await B.page.evaluate(() => { const r = [...window.__r88.game.online.remotes.values()][0]; return r ? JSON.stringify({ name: r.name, foot: !!r.foot, view: !!r.view, driver: !!(r.driver && r.driver.ready), pos: [r.pos.x.toFixed(1), r.pos.y.toFixed(1), r.pos.z.toFixed(1)] }) : 'none'; }));
await A.page.evaluate(() => { const g = window.__r88.game; g.tc.present.year = 1885; }); await wait(2500);
console.log('after A jumps to 1885', JSON.stringify(await st(A.page)), 'B remotes', (await st(B.page)).remotes);
await B.page.evaluate(() => { const g = window.__r88.game; g.tc.present.year = 1885; }); await wait(3000);
console.log('B follows to 1885', JSON.stringify(await st(B.page)));
console.log('errors', JSON.stringify([...A.errors, ...B.errors].slice(0, 8)));
await A.page.evaluate(() => window.__r88.game.online.stop()); await B.page.evaluate(() => window.__r88.game.online.stop());
await wait(800);
await browser.close();
